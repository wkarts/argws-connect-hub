#!/usr/bin/env node

const fs = require('fs');

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const lock = fs.readFileSync('yarn.lock', 'utf8');

if (!lock.startsWith('# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.')) {
  console.error('HUB dependency validation: yarn.lock não parece ser um lockfile Yarn v1 válido.');
  process.exit(1);
}

const dependencyGroups = [
  pkg.dependencies || {},
  pkg.devDependencies || {},
  pkg.optionalDependencies || {},
];

const missing = [];
for (const group of dependencyGroups) {
  for (const [name, spec] of Object.entries(group)) {
    if (/^(file:|link:|workspace:)/.test(spec)) continue;

    const selector = `${name}@${spec}`;
    if (!lock.includes(selector)) missing.push(selector);
  }
}

if (missing.length) {
  console.error('HUB dependency validation: package.json e yarn.lock estão dessincronizados.');
  console.error('Entradas diretas ausentes no yarn.lock:');
  missing.forEach(item => console.error(`  - ${item}`));
  console.error('Execute Yarn 1.22.x para atualizar yarn.lock antes do build.');
  process.exit(1);
}

console.log('HUB dependency validation: package.json e yarn.lock sincronizados.');
